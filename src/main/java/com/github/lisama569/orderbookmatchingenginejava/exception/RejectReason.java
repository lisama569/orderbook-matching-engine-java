package com.github.lisama569.orderbookmatchingenginejava.exception;

/**
 * 可区分的拒绝/失败原因。
 * 下单校验类以 ORDER_ 开头，风控类以 RISK_ 开头，事件重放类以 EVENT_ 开头。
 */
public enum RejectReason {
    ORDER_INVALID_PRICE,
    ORDER_INVALID_QUANTITY,
    ORDER_INVALID_SYMBOL,
    ORDER_UNKNOWN_ACCOUNT,
    ORDER_DUPLICATE_CLIENT_ORDER_ID,

    RISK_INSUFFICIENT_CASH,
    RISK_INSUFFICIENT_POSITION,

    CANCEL_ORDER_NOT_FOUND,
    CANCEL_ORDER_NOT_ACTIVE,
    MODIFY_ORDER_NOT_FOUND,
    MODIFY_ORDER_NOT_ACTIVE,
    MODIFY_INVALID_PRICE,
    MODIFY_INVALID_QUANTITY,
    RISK_MODIFY_INSUFFICIENT_CASH,
    RISK_MODIFY_INSUFFICIENT_POSITION,

    MARKET_NO_LIQUIDITY,

    EVENT_OUT_OF_ORDER,
    EVENT_DUPLICATE_IGNORED,
    EVENT_DUPLICATE_CONFLICT,
    EVENT_LATE,
    EVENT_CANNOT_APPLY
}
